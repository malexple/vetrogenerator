#!/usr/bin/env python3
"""Этап B (только сетка): создаёт каталог расчёта и строит сетку snappyHexMesh.
Пример:
    python3 make_case.py --name t1 --angle 0 --np 8
    python3 make_case.py --name t1 --angle 0 --stl ../geometry/out/shell.stl --lvl 4 5 --cyl-level 5
Ветер идёт вдоль +x. Направление меняется поворотом STL вокруг z.
Единицы: метры.
"""
import argparse, os, shutil, subprocess, sys, textwrap
import numpy as np
import trimesh

HERE = os.path.dirname(os.path.abspath(__file__))
HDR = "FoamFile\n{\n    format ascii;\n    class dictionary;\n    object %s;\n}\n\n"


def w(path, name, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("/* generated by make_case.py */\n" + (HDR % name) + textwrap.dedent(body))


def run(cmd, case, log):
    print(">>", cmd, flush=True)
    with open(os.path.join(case, log), "w") as f:
        r = subprocess.run(cmd, shell=True, cwd=case, stdout=f, stderr=subprocess.STDOUT)
    if r.returncode != 0:
        print(f"ОШИБКА, смотри {case}/{log}")
        print("".join(open(os.path.join(case, log)).readlines()[-25:]))
        sys.exit(r.returncode)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--stl", default=os.path.join(HERE, "..", "geometry", "out", "shell.stl"))
    ap.add_argument("--angle", type=float, default=0.0, help="направление ветра, градусы")
    ap.add_argument("--base", type=float, default=0.15, help="размер базовой ячейки, м")
    ap.add_argument("--lvl", type=int, nargs=2, default=[4, 5], help="уровни измельчения у поверхности (мин макс)")
    ap.add_argument("--cyl-level", type=int, default=5, help="уровень в зоне цилиндра")
    ap.add_argument("--xmin", type=float, default=-3.0)
    ap.add_argument("--xmax", type=float, default=6.0)
    ap.add_argument("--half", type=float, default=3.0, help="полуразмер домена по y и z")
    ap.add_argument("--np", type=int, default=1)
    ap.add_argument("--dry", action="store_true", help="только создать файлы")
    a = ap.parse_args()

    case = os.path.join(HERE, a.name)
    if os.path.exists(case):
        shutil.rmtree(case)
    os.makedirs(os.path.join(case, "constant", "triSurface"))

    m = trimesh.load(a.stl)
    m.apply_transform(trimesh.transformations.rotation_matrix(np.radians(a.angle), [0, 0, 1]))
    txt = m.export(file_type="stl_ascii")
    if isinstance(txt, bytes):
        txt = txt.decode()
    lines = txt.strip().split("\n")
    lines[0] = "solid shell"
    lines[-1] = "endsolid shell"
    open(os.path.join(case, "constant", "triSurface", "shell.stl"), "w").write("\n".join(lines) + "\n")

    nx = int(round((a.xmax - a.xmin) / a.base))
    ny = int(round(2 * a.half / a.base))
    x0, x1, h = a.xmin, a.xmax, a.half
    w(f"{case}/system/blockMeshDict", "blockMeshDict", f"""\
        convertToMeters 1;
        vertices
        (
            ({x0} {-h} {-h}) ({x1} {-h} {-h}) ({x1} {h} {-h}) ({x0} {h} {-h})
            ({x0} {-h} {h}) ({x1} {-h} {h}) ({x1} {h} {h}) ({x0} {h} {h})
        );
        blocks ( hex (0 1 2 3 4 5 6 7) ({nx} {ny} {ny}) simpleGrading (1 1 1) );
        edges ();
        boundary
        (
            inlet  {{ type patch; faces ((0 4 7 3)); }}
            outlet {{ type patch; faces ((1 2 6 5)); }}
            sides  {{ type patch; faces ((0 1 5 4) (3 7 6 2) (0 3 2 1) (4 5 6 7)); }}
        );
        mergePatchPairs ();
        """)
    w(f"{case}/system/controlDict", "controlDict", """\
        application     foamRun;
        solver          incompressibleFluid;
        startFrom       startTime;
        startTime       0;
        stopAt          endTime;
        endTime         1000;
        deltaT          1;
        writeControl    timeStep;
        writeInterval   200;
        purgeWrite      2;
        writeFormat     ascii;
        writePrecision  8;
        runTimeModifiable true;
        """)
    w(f"{case}/system/fvSchemes", "fvSchemes", "ddtSchemes { default steadyState; }\ngradSchemes { default Gauss linear; }\ndivSchemes { default none; }\nlaplacianSchemes { default Gauss linear corrected; }\ninterpolationSchemes { default linear; }\nsnGradSchemes { default corrected; }\n")
    w(f"{case}/system/fvSolution", "fvSolution", "solvers {}\n")
    xl, yl = a.xmin + 0.1, 0.0123
    L0, L1 = a.lvl
    lc = a.cyl_level
    nlevel = " ".join(str(x) for x in range(L0))
    w(f"{case}/system/snappyHexMeshDict", "snappyHexMeshDict", f"""\
        castellatedMesh true;
        snap            true;
        addLayers       false;
        geometry
        {{
            shell {{ type triSurfaceMesh; file "shell.stl"; }}
            cylZone   {{ type searchableBox; min (-0.25 -0.25 -0.6); max (0.25 0.25 0.6); }}
        }}
        castellatedMeshControls
        {{
            maxLocalCells 100000000;
            maxGlobalCells 60000000;
            minRefinementCells 0;
            maxLoadUnbalance 0.10;
            nCellsBetweenLevels 3;
            features ();
            refinementSurfaces
            {{
                shell {{ level ({L0} {L1}); }}
            }}
            resolveFeatureAngle 30;
            refinementRegions
            {{
                cylZone {{ mode inside; level {lc}; }}
            }}
            locationInMesh ({xl} {yl} {yl});
            allowFreeStandingZoneFaces true;
        }}
        snapControls
        {{
            nSmoothPatch 3;
            tolerance 2.0;
            nSolveIter 50;
            nRelaxIter 5;
            nFeatureSnapIter 10;
            implicitFeatureSnap false;
            explicitFeatureSnap false;
            multiRegionFeatureSnap false;
        }}
        addLayersControls
        {{
            relativeSizes true;
            layers {{}};
            expansionRatio 1.2;
            finalLayerThickness 0.3;
            minThickness 0.1;
            nGrow 0;
            featureAngle 60;
            nRelaxIter 3;
            nSmoothSurfaceNormals 1;
            nSmoothNormals 3;
            nSmoothThickness 10;
            maxFaceThicknessRatio 0.5;
            maxThicknessToMedialRatio 0.3;
            minMedialAxisAngle 90;
            nBufferCellsNoExtrude 0;
            nLayerIter 50;
        }}
        meshQualityControls
        {{
            maxNonOrtho 65;
            maxBoundarySkewness 20;
            maxInternalSkewness 4;
            maxConcave 80;
            minVol 1e-13;
            minTetQuality 1e-15;
            minArea -1;
            minTwist 0.02;
            minDeterminant 0.001;
            minFaceWeight 0.05;
            minVolRatio 0.01;
            minTriangleTwist -1;
            nSmoothScale 4;
            errorReduction 0.75;
            relaxed {{ maxNonOrtho 75; }}
        }}
        mergeTolerance 1e-6;
        """)
    if a.np > 1:
        w(f"{case}/system/decomposeParDict", "decomposeParDict", f"numberOfSubdomains {a.np};\nmethod scotch;\n")

    if a.dry:
        print("файлы созданы:", case)
        return
    run("blockMesh", case, "log.blockMesh")
    if a.np > 1:
        run("decomposePar -force", case, "log.decomposePar")
        run(f"mpirun --allow-run-as-root -np {a.np} snappyHexMesh -parallel -overwrite", case, "log.snappyHexMesh")
        run(f"mpirun --allow-run-as-root -np {a.np} checkMesh -parallel -latestTime", case, "log.checkMesh")
        run("reconstructParMesh -constant", case, "log.reconstruct")
    else:
        run("snappyHexMesh -overwrite", case, "log.snappyHexMesh")
        run("checkMesh", case, "log.checkMesh")
    print(subprocess.run("grep -E 'cells:|Mesh OK|Failed|patch' log.checkMesh | head -20", shell=True, cwd=case, capture_output=True, text=True).stdout)
    print("Патчи:", subprocess.run("grep -A40 '^(' constant/polyMesh/boundary | grep -E '^    [a-zA-Z]' ", shell=True, cwd=case, capture_output=True, text=True).stdout)


if __name__ == "__main__":
    main()
